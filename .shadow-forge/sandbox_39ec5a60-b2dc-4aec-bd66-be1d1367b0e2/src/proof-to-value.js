
import { Log } from './core/autonomy/SovereignLogger.js';

/**
 * PH EVO STUDIO — PROOF-TO-VALUE (PRODUCTION GRADE)
 * ═══════════════════════════════════════════════════════════════
 * Maps proof receipts to monetary/business value.
 * Tracks which proofs contributed to deployments, revenue, and user impact.
 */

export class ProofToValue {
  constructor() {
    this.status = 'ACTIVE';
    this.valueLedger = [];
  }

  /**
   * Register a proof receipt and assign a business value to it.
   * @param {Object} proof - { id, claim, evidence, owner, timestamp }
   * @param {Object} value - { type: 'deploy'|'revenue'|'feature'|'bugfix', amount, currency, description }
   */
  registerValue(proof, value) {
    if (!proof || !proof.id) {
      throw new Error('Proof receipt is required');
    }
    const entry = {
      proofId: proof.id,
      claim: proof.claim,
      owner: proof.owner || 'unknown',
      valueType: value?.type || 'feature',
      amount: value?.amount || 0,
      currency: value?.currency || 'USD',
      description: value?.description || '',
      registeredAt: new Date().toISOString(),
    };
    this.valueLedger.push(entry);
    Log.info(`[ProofToValue] Registered value: ${entry.valueType} ($${entry.amount}) for proof ${entry.proofId}`);
    return entry;
  }

  /**
   * Calculate total value generated by all registered proofs.
   */
  getTotalValue() {
    return this.valueLedger.reduce((sum, e) => sum + (e.amount || 0), 0);
  }

  /**
   * Get value breakdown by type.
   */
  getValueBreakdown() {
    const breakdown = {};
    this.valueLedger.forEach(e => {
      const t = e.valueType;
      if (!breakdown[t]) breakdown[t] = { count: 0, total: 0 };
      breakdown[t].count += 1;
      breakdown[t].total += e.amount || 0;
    });
    return breakdown;
  }

  /**
   * Get the top N most valuable proofs.
   */
  getTopProofs(n = 10) {
    return [...this.valueLedger]
      .sort((a, b) => b.amount - a.amount)
      .slice(0, n);
  }

  async execute(params = {}) {
    Log.info('[ProofToValue] Executing value calculation...');
    if (params.proof && params.value) {
      const entry = this.registerValue(params.proof, params.value);
      return { success: true, timestamp: new Date().toISOString(), entry };
    }
    return {
      success: true,
      timestamp: new Date().toISOString(),
      totalValue: this.getTotalValue(),
      breakdown: this.getValueBreakdown(),
      topProofs: this.getTopProofs(5),
      ledgerSize: this.valueLedger.length,
    };
  }

  getStatus() {
    return {
      id: 'proof-to-value',
      grade: this.valueLedger.length > 0 ? 'S+++++' : 'IDLE',
      state: 'ACTIVE',
      resonance: 0.99,
      totalValue: this.getTotalValue(),
    };
  }
}
